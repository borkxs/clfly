import { spawn } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { runLs, which } from "../registry/link.js";

export interface McpTool {
  name: string;
  description?: string;
  inputSchema?: { properties?: Record<string, unknown>; required?: string[] };
}

export type ListTools = (bin: string, cwd: string) => Promise<McpTool[]>;

export interface TreeSummary {
  name: string;
  path: string;
  description?: string;
  harnesses: string[];
  commands: Array<{ path: string[]; description?: string; required: string[] }>;
  error?: string;
}

function oneLine(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/**
 * Ask a tree for its commands through its own `mcp serve`. Trees load their
 * command files with their own loader (often tsx), so importing them from here
 * is not reliable; the MCP tool list is what every tree already serves.
 */
export const listToolsOverMcp: ListTools = (bin, cwd) =>
  new Promise((resolve, reject) => {
    const child = spawn(bin, ["mcp", "serve"], { cwd, stdio: ["pipe", "pipe", "ignore"] });
    let buffer = "";
    const timer = setTimeout(() => {
      child.kill();
      reject(new Error(`${bin} mcp serve did not answer tools/list within 20s`));
    }, 20_000);
    const finish = (fn: () => void) => {
      clearTimeout(timer);
      child.kill();
      fn();
    };
    child.on("error", (err) => finish(() => reject(err)));
    child.stdout.on("data", (chunk: Buffer) => {
      buffer += chunk.toString("utf8");
      let nl: number;
      while ((nl = buffer.indexOf("\n")) >= 0) {
        const line = buffer.slice(0, nl).trim();
        buffer = buffer.slice(nl + 1);
        if (!line) continue;
        let msg: { id?: number; result?: { tools?: McpTool[] }; error?: { message?: string } };
        try {
          msg = JSON.parse(line);
        } catch {
          continue;
        }
        if (msg.id !== 2) continue;
        if (msg.error) finish(() => reject(new Error(msg.error?.message ?? "tools/list failed")));
        else finish(() => resolve(msg.result?.tools ?? []));
      }
    });
    const send = (msg: unknown) => child.stdin.write(`${JSON.stringify(msg)}\n`);
    send({
      jsonrpc: "2.0",
      id: 1,
      method: "initialize",
      params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "clfly-memory", version: "0" } },
    });
    send({ jsonrpc: "2.0", method: "notifications/initialized" });
    send({ jsonrpc: "2.0", id: 2, method: "tools/list" });
  });

export async function summarizeTree(input: {
  name: string;
  path: string;
  harnesses: string[];
  bin: string | null;
  listTools?: ListTools;
}): Promise<TreeSummary> {
  const summary: TreeSummary = { name: input.name, path: input.path, harnesses: input.harnesses, commands: [] };
  try {
    const pkg = JSON.parse(readFileSync(join(input.path, "package.json"), "utf8")) as { description?: string };
    if (pkg.description) summary.description = oneLine(pkg.description);
    if (!input.bin) throw new Error(`${input.name} is not on PATH`);
    const tools = await (input.listTools ?? listToolsOverMcp)(input.bin, input.path);
    summary.commands = tools
      .map((tool) => ({
        path: tool.name.split("_"),
        description: tool.description ? oneLine(tool.description) : undefined,
        required: tool.inputSchema?.required ?? [],
      }))
      .sort((a, b) => a.path.join(" ").localeCompare(b.path.join(" ")));
  } catch (err) {
    summary.error = err instanceof Error ? err.message : String(err);
  }
  return summary;
}

/** Claude Code memory file (frontmatter + body) listing every linked tree and its commands. */
export function renderMemory(input: { name: string; trees: TreeSummary[] }): string {
  const names = input.trees.map((t) => t.name).join(", ");
  const lines = [
    "---",
    `name: ${input.name}`,
    `description: ${JSON.stringify(
      `Erik's own CLIs (clfly trees: ${names}) and every command. Check here before guessing what a bare word like "pm" or "run" means.`,
    )}`,
    "metadata:",
    "  type: reference",
    "---",
    "",
    "Generated by `clfly memory` from the clfly registry; edits are overwritten. Each tree is a bin on PATH.",
    "Trees registered with a harness are also MCP tools named `mcp__<tree>__<command>` (spaces become `_`).",
    "`<x>` marks a required arg. Flags: `<tree> <command> --help`. Change a tree in its source path, not by hand.",
  ];
  for (const tree of input.trees) {
    const desc = tree.description ? ` — ${tree.description}` : "";
    const mcp = tree.harnesses.length > 0 ? ` · MCP: ${tree.harnesses.join(", ")}` : "";
    lines.push("", `## ${tree.name}${desc}`, "", `\`${tree.path}\`${mcp}`, "");
    if (tree.error) {
      lines.push(`- (could not list commands: ${oneLine(tree.error)})`);
      continue;
    }
    for (const cmd of tree.commands) {
      const usage = [tree.name, ...cmd.path, ...cmd.required.map((r) => `<${r}>`)].join(" ");
      const what = cmd.description ? ` — ${cmd.description}` : "";
      lines.push(`- \`${usage}\`${what}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

/** Write the memory file for all non-stale linked trees. Rewrites only when the content changed. */
export async function writeMemory(options: {
  env: NodeJS.ProcessEnv;
  outFile: string;
  name?: string;
  listTools?: ListTools;
}): Promise<{ outFile: string; trees: string[]; failed: string[]; changed: boolean }> {
  const { rows } = runLs({ env: options.env, prune: false });
  const trees = await Promise.all(
    rows
      .filter((row) => !row.stale)
      .map((row) =>
        summarizeTree({
          name: row.name,
          path: row.path,
          harnesses: row.harnesses,
          bin: which(row.name, options.env),
          listTools: options.listTools,
        }),
      ),
  );
  const body = renderMemory({ name: options.name ?? "clfly-trees", trees });
  let previous: string | undefined;
  try {
    previous = readFileSync(options.outFile, "utf8");
  } catch {
    previous = undefined;
  }
  const changed = previous !== body;
  if (changed) {
    mkdirSync(dirname(options.outFile), { recursive: true });
    writeFileSync(options.outFile, body);
  }
  return {
    outFile: options.outFile,
    trees: trees.map((t) => t.name),
    failed: trees.filter((t) => t.error).map((t) => t.name),
    changed,
  };
}
