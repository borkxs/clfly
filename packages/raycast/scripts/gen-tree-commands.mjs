#!/usr/bin/env node
// Hoist every linked clfly tree to a top-level Raycast command, so typing "pm" in root search opens pm.
// Raycast reads commands from package.json at build time, so rerun after linking or unlinking a tree:
//   npm run gen-trees            (uses `clfly` on PATH, or CLFLY_BIN)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bin = process.env.CLFLY_BIN || "clfly";
const { trees } = JSON.parse(execFileSync(bin, ["manifest", "--json"], { encoding: "utf8", maxBuffer: 64 << 20 }));
const PREFIX = "tree-";
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const src = join(root, "src");
for (const f of readdirSync(src)) if (f.startsWith(PREFIX) && f.endsWith(".tsx")) unlinkSync(join(src, f));

const generated = trees
  .filter((t) => !t.error)
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((t) => {
    const name = PREFIX + slug(t.name);
    writeFileSync(
      join(src, `${name}.tsx`),
      `// Generated by scripts/gen-tree-commands.mjs; do not edit.\nimport { TreeRoot } from "./components/TreeRoot";\n\nexport default function Command() {\n  return <TreeRoot name=${JSON.stringify(t.name)} />;\n}\n`,
    );
    const description = (t.description || `${t.name} commands`).split(/(?<=[.:;])\s/)[0].slice(0, 120);
    return { name, title: t.name, subtitle: "clfly", description, mode: "view" };
  });

const pkgPath = join(root, "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
pkg.commands = [...pkg.commands.filter((c) => !c.name.startsWith(PREFIX)), ...generated];
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log(`${generated.length} tree commands: ${generated.map((c) => c.title).join(", ")}`);
